    Read-only. Checks that the scanner and its scheduled task are installed as expected and
    that this device has recent scan results. Writes a single line:
        Compliant
        NonCompliant: <reason>;<reason>...
    Compliance rule: the value returned by the script Equals  Compliant
    with "Run the specified remediation script when this setting is noncompliant" ticked.

    Reasons the remediation script fixes:   ScannerMissing, ScannerChanged, TaskMissing,
                                            TaskDisabled, TaskOutdated, NeverScanned,
