$ScannerVersion = '2.0.0'
$ScannerSha256  = '4B2C8291FBF7AB9D2CB8F6C19457A4A379225FAE86BBB988D16697C2ECF7E3DF'
$TaskSignature  = 'v2.0.0;Wednesday;12:00;4h;RemoteSigned;60m'
$MaxAgeDays     = 10

$InstallDir  = Join-Path $env:ProgramData 'DotNetDependencyScan'
$ScannerPath = Join-Path $InstallDir 'Invoke-DotNetDependencyScan.ps1'
$TaskName    = 'DotNetDependencyScan'

try {
    $reasons = New-Object System.Collections.Generic.List[string]

    if (-not (Test-Path -LiteralPath $ScannerPath -PathType Leaf)) {
        $reasons.Add('ScannerMissing')
    } elseif ((Get-FileHash -LiteralPath $ScannerPath -Algorithm SHA256).Hash -ne $ScannerSha256) {
        $reasons.Add('ScannerChanged')
    }

    $task = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction SilentlyContinue
    $taskRunning = $task -and $task.State -eq 'Running'
    if (-not $task) {
        $reasons.Add('TaskMissing')
    } else {
        if ($task.State -eq 'Disabled') { $reasons.Add('TaskDisabled') }
        $actionOk = @($task.Actions | Where-Object { "$($_.Arguments)".Contains($ScannerPath) }).Count -gt 0
        if (-not $actionOk -or -not "$($task.Description)".Contains("[$TaskSignature]")) { $reasons.Add('TaskOutdated') }
    }

    # While the task is running, its results are on their way; don't judge the old ones.
    if (-not $taskRunning) {
        $status = Get-CimInstance -Namespace 'root\cimv2' -ClassName 'CM_DotNetScanStatus' -ErrorAction SilentlyContinue |
            Select-Object -First 1
        if (-not $status) {
            $reasons.Add('NeverScanned')
        } elseif ($status.ScanTime -lt (Get-Date).AddDays(-$MaxAgeDays)) {
            $reasons.Add('ScanStale')
        } elseif ($status.ScannerVersion -ne $ScannerVersion) {
            $reasons.Add('ScanFromOldVersion')
        } elseif ($status.Result -ne 'Success') {
            $reasons.Add("LastScan$($status.Result)")
        }
    }

    if ($reasons.Count -eq 0) { 'Compliant' } else { 'NonCompliant: ' + ($reasons -join ';') }
} catch {
    "NonCompliant: DiscoveryError $($_.Exception.Message)"
}
