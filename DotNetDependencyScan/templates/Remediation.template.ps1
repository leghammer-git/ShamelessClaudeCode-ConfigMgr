$ScannerVersion      = '__SCANNER_VERSION__'
$ScannerSha256       = '__SCANNER_SHA256__'
$TaskSignature       = '__TASK_SIGNATURE__'
$TaskExecutionPolicy = '__TASK_EXECUTION_POLICY__'   # RemoteSigned | AllSigned | Inherit (omit the switch)
$ScheduleDay         = '__SCHEDULE_DAY__'
$ScheduleTime        = '__SCHEDULE_TIME__'
$RandomDelayHours    = __RANDOM_DELAY_HOURS__
$TimeBudgetMinutes   = __TIME_BUDGET_MINUTES__
$MaxAgeDays          = __MAX_AGE_DAYS__

$InstallDir  = Join-Path $env:ProgramData 'DotNetDependencyScan'
$ScannerPath = Join-Path $InstallDir 'Invoke-DotNetDependencyScan.ps1'
$TaskName    = 'DotNetDependencyScan'
$RegistryKey = 'HKLM:\SOFTWARE\DotNetDependencyScan'
$LogPath     = Join-Path $env:WINDIR 'Logs\DotNetDependencyScan.log'

function Write-RemediationLog {
    param([Parameter(Mandatory)][string]$Message, [ValidateSet('Info', 'Warning', 'Error')][string]$Severity = 'Info')
    $now = Get-Date
    $bias = -[TimeZoneInfo]::Local.GetUtcOffset($now).TotalMinutes
    $line = '<![LOG[{0}]LOG]!><time="{1}{2:+0;-0;+0}" date="{3}" component="Remediation" context="" type="{4}" thread="{5}" file="">' -f `
        $Message, $now.ToString('HH:mm:ss.fff'), $bias, $now.ToString('MM-dd-yyyy'),
        @{ Info = 1; Warning = 2; Error = 3 }[$Severity], $PID
    try { Add-Content -LiteralPath $LogPath -Value $line -Encoding UTF8 -ErrorAction Stop } catch { }
}

function Set-InstallFolder {
    if (-not (Test-Path -LiteralPath $InstallDir)) { New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null }
    $system = New-Object System.Security.Principal.SecurityIdentifier 'S-1-5-18'
    $admins = New-Object System.Security.Principal.SecurityIdentifier 'S-1-5-32-544'
    $acl = New-Object System.Security.AccessControl.DirectorySecurity
    $acl.SetOwner($admins)
    $acl.SetAccessRuleProtection($true, $false)
    foreach ($sid in $system, $admins) {
        $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule -ArgumentList `
                    $sid, 'FullControl', 'ContainerInherit, ObjectInherit', 'None', 'Allow'))
    }
    Set-Acl -LiteralPath $InstallDir -AclObject $acl
}

function Install-Scanner {
    # Same normalisation as Build-CIScripts.ps1, so the bytes (and hash) always match.
    $text = (($ScannerText -replace "`r`n", "`n") -replace "`n", "`r`n").TrimEnd() + "`r`n"
    # Delete first so the new file inherits the folder's locked-down ACL.
    if (Test-Path -LiteralPath $ScannerPath) { Remove-Item -LiteralPath $ScannerPath -Force }
    [IO.File]::WriteAllText($ScannerPath, $text, (New-Object System.Text.UTF8Encoding $true))
    $hash = (Get-FileHash -LiteralPath $ScannerPath -Algorithm SHA256).Hash
    if ($hash -ne $ScannerSha256) {
        throw "Scanner hash after writing is $hash, expected $ScannerSha256. Rebuild the CI scripts with Build-CIScripts.ps1."
    }
}

function Register-ScanTask {
    $arguments = '-NoProfile -NonInteractive'
    if ($TaskExecutionPolicy -ne 'Inherit') { $arguments += " -ExecutionPolicy $TaskExecutionPolicy" }
    $arguments += ' -File "{0}" -TimeBudgetMinutes {1}' -f $ScannerPath, $TimeBudgetMinutes

    $action = New-ScheduledTaskAction -Execute (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe') -Argument $arguments
    $trigger = New-ScheduledTaskTrigger -Weekly -DaysOfWeek $ScheduleDay -At $ScheduleTime -RandomDelay (New-TimeSpan -Hours $RandomDelayHours)
    $principal = New-ScheduledTaskPrincipal -UserId 'NT AUTHORITY\SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
        -MultipleInstances IgnoreNew -Priority 7 -ExecutionTimeLimit (New-TimeSpan -Minutes ($TimeBudgetMinutes + 30))
    $description = ('Inventories .NET runtime dependencies to WMI for ConfigMgr hardware inventory. ' +
        'Managed by the DotNetDependencyScan configuration item; manual changes are reverted. [{0}]') -f $TaskSignature

    Register-ScheduledTask -TaskPath '\' -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal `
        -Settings $settings -Description $description -Force | Out-Null
}

function Invoke-Remediation {
    $ErrorActionPreference = 'Stop'
    $done = New-Object System.Collections.Generic.List[string]
    Write-RemediationLog "Remediation for DotNetDependencyScan $ScannerVersion starting"

    Set-InstallFolder
    $installed = if (Test-Path -LiteralPath $ScannerPath) { (Get-FileHash -LiteralPath $ScannerPath -Algorithm SHA256).Hash }
    if ($installed -ne $ScannerSha256) {
        Install-Scanner
        $done.Add('ScannerInstalled')
        Write-RemediationLog "Installed scanner $ScannerVersion to $ScannerPath (SHA256 $ScannerSha256)"
    }

    $task = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction SilentlyContinue
    $actionOk = $task -and @($task.Actions | Where-Object { "$($_.Arguments)".Contains($ScannerPath) }).Count -gt 0
    if (-not $task -or -not $actionOk -or -not "$($task.Description)".Contains("[$TaskSignature]")) {
        Register-ScanTask
        $done.Add('TaskRegistered')
        Write-RemediationLog "Registered scheduled task \$TaskName ($ScheduleDay $ScheduleTime, up to ${RandomDelayHours}h random delay)"
    } elseif ($task.State -eq 'Disabled') {
        Enable-ScheduledTask -TaskPath '\' -TaskName $TaskName | Out-Null
        $done.Add('TaskEnabled')
        Write-RemediationLog "Re-enabled scheduled task \$TaskName" -Severity Warning
    }

    if (-not (Test-Path -LiteralPath $RegistryKey)) { New-Item -Path $RegistryKey | Out-Null }
    Set-ItemProperty -LiteralPath $RegistryKey -Name 'ScannerVersion' -Value $ScannerVersion
    Set-ItemProperty -LiteralPath $RegistryKey -Name 'ScannerSha256' -Value $ScannerSha256
    Set-ItemProperty -LiteralPath $RegistryKey -Name 'LastRemediation' -Value (Get-Date -Format 's')

    # Rescan if results are missing, stale or from an older scanner. Failed or partial scans
    # are left for the weekly run (and flagged by discovery) rather than retried daily.
    $status = Get-CimInstance -Namespace 'root\cimv2' -ClassName 'CM_DotNetScanStatus' -ErrorAction SilentlyContinue |
        Select-Object -First 1
    $needsScan = (-not $status) -or ($status.ScanTime -lt (Get-Date).AddDays(-$MaxAgeDays)) -or ($status.ScannerVersion -ne $ScannerVersion)
    $task = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName
    if ($needsScan -and $task.State -ne 'Running') {
        Start-ScheduledTask -TaskPath '\' -TaskName $TaskName
        $done.Add('ScanStarted')
        Write-RemediationLog 'Started a scan because this device has no current results'
    }

    if ($done.Count -eq 0) { $done.Add('NothingToDo') }
    Write-RemediationLog "Remediation finished: $($done -join ';')"
    'Remediated: ' + ($done -join ';')
}

